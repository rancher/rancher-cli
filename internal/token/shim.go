// legacyTokenCmd is the compatibility shim for Rancher-generated kubeconfigs,
// which invoke `rancher token --server=<url> --user=<name> [--cluster=<id>]`
// (the legacy CLI's exec-credential plugin). It adapts the legacy flags onto
// the native get-token machinery. --user is a cache-slot component and the
// basic-auth username default; it carries no principal claim and does not
// select among stored login credentials - stored-login selection follows the
// same server-ranking a nameless native call uses (current server, then sorted
// name). Deprecated by design - it retires with the kubeconfigs that need it;
// agents and new kubeconfigs use `auth get-token`.
//
// The `token` entry in root.go is marked bare: adaptEntry never calls
// resolveDeps before Execute, so the shim adds no config load of its own.
// Execute resolves the config dir itself via config.ResolveDir (no
// config.yaml parse) and probes token-cache.yaml directly; what it judges a
// record against is the snapshot the root hook already made, and a
// config.yaml the root hook could not read leaves none, so every record is
// a miss. The store is constructed lazily on a cache miss only.
type legacyTokenCmd struct {
	// dir and store are pre-populated in test wiring and non-bare paths;
	// both are zero in bare dispatch, resolved lazily in Execute.
	dir   string
	store config.CredStore
	// anchor is what a cache hit is judged against. Zero in bare
	// dispatch, where the invocation's own anchor - the one the root hook
	// built beside its config snapshot - is used instead.
	anchor *config.CacheAnchor
}

// NewLegacyTokenCommand builds the `token` shim command. dir and store are
// used when provided (test/non-bare wiring); when both are zero Execute
// resolves them from the input flags.
func NewLegacyTokenCommand(dir string, store config.CredStore, anchor *config.CacheAnchor) runtime.Command {
	return &legacyTokenCmd{dir: dir, store: store, anchor: anchor}
}

func (legacyTokenCmd) Describe() runtime.Descriptor {
	return runtime.Descriptor{
		Name:  "token",
		Usage: "Legacy exec-credential shim for Rancher-generated kubeconfigs",
		Desc: "Compatibility adapter for kubeconfigs generated by Rancher " +
			"with kubeconfig-generate-token disabled, which invoke the " +
			"legacy CLI's `rancher token`. New integrations and agents " +
			"use `auth get-token`; this command exists so existing " +
			"kubeconfigs keep working after swapping the binary. " +
			"--user is the cache-slot key and basic-auth username default; " +
			"stored-login selection follows server-ranking, not --user.",
		CommandType: runtime.Local,
		Flags: []runtime.ArgSpec{
			{Name: "server", Type: "string", Required: true, Desc: "Rancher server `url` (https assumed when schemeless)"},
			{Name: "user", Type: "string", Required: true, Desc: "kubeconfig user `name` (as generated by Rancher)"},
			{Name: "cluster", Type: "string", Desc: "cluster `id` for a cluster-scoped token (set by Authorized Cluster Endpoint kubeconfigs)"},
			{Name: "auth-provider", Type: "string", Desc: "auth provider `name` to sign in with"},
			{Name: "auth-flow", Type: "string", Enum: []string{"devicecode", "authcode"}, Desc: "identity-provider `flow`", Env: []string{config.EnvOAuthAuthFlow, config.EnvLegacyOAuthAuthFlow}},
			{Name: "cacerts", Type: "string", Desc: "PEM CA bundle `path` (legacy spelling of --cacert)"},
			{Name: "skip-verify", Type: "bool", Desc: "skip TLS verification (insecure)"},
		},
		Network: true,
		Auth:    true,
		Examples: []string{
			"rancher token --server https://rancher.example.com --user my-cluster",
		},
		// Same policy as auth get-token: a bare ExecCredential object on
		// stdout, no envelope to vary with -o.
		OutputPolicy: runtime.OutputPolicy{AllowedFormats: []string{"table", "json"}},
		Shape:        runtime.ShapeExecJSON,
	}
}

func (c legacyTokenCmd) Execute(ctx context.Context, in runtime.Input, p runtime.Prompter) (runtime.Result, error) {
	// Normalize once: trimmed value is used for the cache-slot name, the
	// basic-auth prompt default, AND the emptiness check. A padded value
	// ("  alice", "alice\n") from a templated or hand-edited kubeconfig must
	// hit the same cache slot as the canonical form.
	user := strings.TrimSpace(in.String("user"))
	if user == "" {
		return runtime.Result{}, clierr.New(clierr.CodeValidation,
			"--user must not be empty; the kubeconfig exec-credential section should supply the user name")
	}
	name := config.LegacyCachePrefix + user
	// Same whitespace-passes-Required gap as --user: a blank --server must
	// fail loudly here, never fall through to resolveConn's config fallback
	// and silently create against the stored current server.
	server := strings.TrimSpace(in.String("server"))
	if server == "" {
		return runtime.Result{}, clierr.New(clierr.CodeValidation,
			"--server must not be empty; the kubeconfig exec-credential section should supply the server URL")
	}
	cluster := strings.TrimSpace(in.String("cluster"))

	// Resolve the config directory via ResolveDir only - never config.Load.
	// The shim adds no config load of its own; what it judges a cache
	// record against is the snapshot the root hook already made.
	dir := c.dir
	if dir == "" {
		var err error
		dir, err = config.ResolveDir(in.String("config"))
		if err != nil {
			return runtime.Result{}, err
		}
	}

	// Fast path: probe token-cache.yaml directly, with no config load of
	// its own. A config.yaml the root hook could not read leaves no
	// snapshot, and a record whose owner cannot be checked is a miss:
	// after a re-login as another user it is the previous user's cluster
	// credential.
	anchor := shimAnchor(dir, c.anchor)
	probedKey, noticed, r, hit, warn := shimProbeFlagCache(dir, name, server, cluster, anchor, p)
	if hit {
		return r, nil
	}

	// Cache miss: resolve the store lazily (config.yaml is needed for the
	// credential-store policy; only runs on the slow path).
	// config.LoadAndStore encapsulates the Load + NewLazyStore pairing used
	// here and in resolveDeps (internal/cli/adapter.go), so a future change to
	// that pairing (e.g. a migration check) stays in one place.
	store := c.store
	if store == nil {
		var serr error
		_, store, serr = config.LoadAndStore(dir)
		if serr != nil {
			// warn (the fast-path probe's loose-permission finding) must
			// ride this error: the probe's global dedup already marked the
			// path seen, so no later read can re-surface it.
			if warn != "" {
				return runtime.Result{}, config.WithNotices(serr, []string{warn})
			}
			return runtime.Result{}, serr
		}
	}

	// The anchor rides into the slow path too: its cache re-check on the
	// resolved key judges records by the same anchor the fast path used,
	// and a command built without one serves nothing from the cache.
	res, err := tokenCmd{dir: dir, store: store, anchor: anchor}.runWithParams(ctx, runParams{
		Server: server,
		// The slot namespaces the legacy user under the "legacy:" prefix, which
		// the native get-token command rejects as a --name value, so shim entries
		// and native entries cannot collide in the exec-credential cache.
		Name:            name,
		Cluster:         cluster,
		AuthProvider:    strings.TrimSpace(in.String("auth-provider")),
		AuthFlow:        strings.TrimSpace(in.String("auth-flow")),
		CACert:          strings.TrimSpace(in.String("cacerts")),
		SkipVerify:      in.Bool("skip-verify"),
		UsernameDefault: user,
		ProbedKey:       probedKey,
		ProbedNoticed:   noticed,
		legacyShim:      true,
	}, p)
	// The `token` entry is bare: no NoticeSource is ever wired onto
	// IO.Notices for this command, so notices the store buffered during the
	// credential work above (a first-run keychain-unavailable fallback, a
	// loose-permission finding) have no pipeline drain. Drain them here, on
	// success and failure alike, and ride them on the Result or error - a
	// ShapeExecJSON result mirrors every warning to stderr as a
	// "# warning:" line under every format, and kubectl surfaces an
	// exec-credential plugin's stderr.
	var notices []string
	if ns, ok := store.(runtime.NoticeSource); ok {
		notices = ns.DrainNotices()
	}
	// warn (the fast-path probe's loose-permission finding, if any) is
	// independent of hit/miss AND of success/failure: the probe's global
	// dedup already marked the path seen, so this is the only carrier left.
	// The probe ran before any store work - it delivers first.
	if warn != "" {
		notices = append([]string{warn}, notices...)
	}
	if err != nil {
		return runtime.Result{}, config.WithNotices(err, notices)
	}
	res.Warnings = append(notices, res.Warnings...)
	return res, nil
}

// shimAnchor is the anchor this invocation judges cache records against:
// the one it was given, else the one the root hook left for the process.
// An anchor built for a different directory than the one this command
// resolved answers for nothing here, so it is discarded rather than
// consulted: the stamp and the config it holds describe somewhere else.
func shimAnchor(dir string, given *config.CacheAnchor) *config.CacheAnchor {
	anchor := given
	if anchor == nil {
		anchor = config.ProcessCacheAnchor()
	}
	if !anchor.SameDirectory(dir) {
		return nil
	}
	return anchor
}

// shimProbeFlagCache is the shim's fast-path cache probe: reads token-cache.yaml
// directly via config.ReadOnlyCachedCred - no config.yaml parse required. The
// probe itself is probeCacheWith (shared with probeFlagCache), so key
// computation, hit construction, and the hit/miss/notice classification stay
// in one place. Returns (key, noticed, result, hit, warn). noticed is true
// when the probe fired a "cache read failed" notice (a real, non-ErrNoToken
// error); the caller sets ProbedNoticed so runWithParams's resolved-key
// re-check is quiet only when the fast path already emitted a notice - a
// clean miss does NOT silence a distinct error on the resolved key
// (notice-zero fix). warn is ReadOnlyCachedCred's standalone-function
// return notice (a loose-permission finding on token-cache.yaml) - already
// folded into r.Warnings on a hit; the caller must still carry it forward
// on a miss, since r is discarded there.
// The anchor is the one the root hook built for this invocation: the
// binding stamp it read before its config load, paired with that load's
// snapshot. The shim adds no config load of its own, and a snapshot the
// root hook could not produce - an unreadable or unparseable config.yaml -
// makes every record a miss. That is a guarantee this command used to
// give the other way round: the fast path existed so a broken config
// could not block a warm hit. It cannot any more, because a record whose
// binding cannot be checked is the previous user's credential after a
// re-login, and serving it is the defect this whole change closes.
// A record this probe judges away is reported as a miss and left where
// it is. Deleting it belongs to the store-backed readers, and the shim's
// slow path reaches that prune only when the key it resolves differs
// from the one probed here, which for the shim it does not: its records
// outlive their binding and are removed when they expire. They are never
// served in the meantime - the binding id decides that - so this is
// hygiene rather than safety.
//
// anchor is already resolved by shimAnchor - resolving it a second time
// here could reach a different answer than the caller's, and then the two
// halves of one invocation would judge records by two anchors.
func shimProbeFlagCache(dir, name, server, cluster string, anchor *config.CacheAnchor, p runtime.Prompter) (key string, noticed bool, r runtime.Result, hit bool, warn string) {
	return probeCacheWith(name, server, cluster, func(k string) (string, time.Time, string, error) {
		type read struct {
			token  string
			expiry time.Time
		}
		// The loose-permission notice belongs to the file, not to the
		// record: it is found on the way in and has to reach the caller
		// whether the record is served, judged away, or absent.
		var notice string
		got, ok, err := config.CachedHit(anchor, func(a *config.CacheAnchor) (read, bool, error) {
			tok, expiry, n, rerr := config.ReadOnlyCachedCred(dir, k, a)
			if n != "" {
				notice = n
			}
			if rerr != nil {
				if errors.Is(rerr, config.ErrNoToken) {
					return read{}, false, nil
				}
				return read{}, false, rerr
			}
			return read{token: tok, expiry: expiry}, true, nil
		})
		if err != nil {
			return "", time.Time{}, notice, err
		}
		if !ok {
			return "", time.Time{}, notice, config.ErrNoToken
		}
		return got.token, got.expiry, notice, nil
	}, p)
}
